#!/usr/bin/env bash
# Rebuilds assets/vendor-pinned/prosemirror.bundle.js from the EXACT versions
# pinned in package.json / package-lock.json. Run from anywhere:
#   resources/prosemirror-bundle/build.sh
# Needs node + npm on the host (not the PHP container). Commit the output.
set -euo pipefail
cd "$(dirname "$0")"
npm ci --no-audit --no-fund
OUT=../../assets/vendor-pinned/prosemirror.bundle.js
{
  echo "/* ProseMirror bundle — GENERATED by resources/prosemirror-bundle/build.sh, do not edit."
  node -e 'const p=require("./package-lock.json").packages;for(const k of Object.keys(p).filter(k=>k.startsWith("node_modules/")&&!k.includes("esbuild")).sort())console.log(" * "+k.slice(13)+"@"+p[k].version)'
  echo " * MIT licensed (https://prosemirror.net). */"
} > "$OUT"
npx esbuild entry.js --bundle --format=esm --minify --legal-comments=none --target=es2020 >> "$OUT"
rm -rf node_modules
echo "Wrote $OUT ($(wc -c < "$OUT") bytes)"
